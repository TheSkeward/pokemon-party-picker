/**
 * @fileoverview Generates a generation's type chart from {@code @pkmn/dex}:
 * the ordered analysis type list (coverage vectors index by it), per
 * defending type the damage-taken code from each attacking type — 1 weak,
 * 2 resist, 3 immune, omitted when neutral — the same codes the dex stores,
 * and the share of the generation's progression species carrying each type
 * combination (mono-types and pairs alike): the reference defender's
 * fractional types (damage-model.js), read by moves whose damage depends on
 * the defender's type, such as Synchronoise. Pairs are kept whole rather
 * than split into per-type shares because types do not occur independently
 * (Normal/Flying, Bug/Flying, Water/Ground are common pairings).
 *
 *   node scripts/build-type-chart.mjs [gen]
 */

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { Dex } from '@pkmn/dex';

// Fixed order shared by every generation that has the type; a generation
// without a type (Fairy before Gen 6) simply omits it, so positions of the
// remaining types are unchanged.
const CANONICAL_ORDER = [
  'Normal', 'Fire', 'Water', 'Electric', 'Grass', 'Ice', 'Fighting', 'Poison',
  'Ground', 'Flying', 'Psychic', 'Bug', 'Rock', 'Ghost', 'Dragon', 'Dark',
  'Steel', 'Fairy',
];

// The share of the generation's progression species carrying each type
// combination, keyed "Type" or "Type1/Type2" in analysis-grid order, rounded
// to four places. Shares sum to one over combinations.
async function typeCombinationShares(gen, dex, types) {
  const modulePath = path.resolve(
    'src', 'generated', `gen${gen}ProgressionSpecies.generated.js`);
  const module = await import(pathToFileURL(modulePath).href);
  const species = Object.keys(module[`GEN${gen}_PROGRESSION_SPECIES`]);
  const order = new Map(types.map((type, index) => [type, index]));
  const counts = new Map();
  let counted = 0;
  for (const id of species) {
    const entry = dex.species.get(id);
    if (!entry?.exists) continue;
    const combination = [...new Set(entry.types)]
      .filter((type) => order.has(type))
      .sort((a, b) => order.get(a) - order.get(b))
      .join('/');
    if (!combination) continue;
    counted += 1;
    counts.set(combination, (counts.get(combination) || 0) + 1);
  }
  return Object.fromEntries(
    [...counts]
      .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
      .map(([combination, count]) => [
        combination,
        Number((count / counted).toFixed(4)),
      ]),
  );
}

async function main() {
  const gen = Number(process.argv[2] || 7);
  if (!Number.isInteger(gen) || gen < 1 || gen > 9) {
    throw new Error(`Unsupported generation: ${process.argv[2]}`);
  }
  const dex = Dex.forGen(gen);
  // The dex marks a type outside the generation as nonstandard ("Future").
  const types = CANONICAL_ORDER.filter((name) => {
    const type = dex.types.get(name);
    return type.exists && !type.isNonstandard;
  });
  const damageTaken = {};
  for (const defense of types) {
    const row = {};
    for (const attack of types) {
      const code = dex.types.get(defense).damageTaken[attack] || 0;
      if (code) row[attack] = code;
    }
    damageTaken[defense] = row;
  }

  const combinationShares = await typeCombinationShares(gen, dex, types);

  const outPath = path.resolve(
    'src', 'generated', `gen${gen}TypeChart.generated.js`);
  const body = `// Generated by scripts/build-type-chart.mjs from @pkmn/dex Gen ${gen} data.
// Do not edit by hand.

// The generation's types in analysis-grid order.
export const GEN${gen}_TYPES = ${JSON.stringify(types)};

// Per defending type, damage-taken code by attacking type: 1 weak, 2 resist,
// 3 immune; neutral pairs are omitted.
export const GEN${gen}_TYPE_DAMAGE_TAKEN = ${JSON.stringify(damageTaken)};

// The share of the generation's progression species carrying each type
// combination ("Type" or "Type1/Type2"): the reference defender's fractional
// types.
export const GEN${gen}_TYPE_COMBINATION_SHARES = ${JSON.stringify(combinationShares)};
`;
  fs.writeFileSync(outPath, body);
  console.log(
    `Wrote Gen ${gen} type chart: ${types.length} types, ${
      Object.keys(combinationShares).length} type combinations.`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
