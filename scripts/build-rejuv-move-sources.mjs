/**
 * @fileoverview Generates src/generated/rejuvMoveSources.generated.js: the
 * machines Rejuvenation distributes (TM, HM, and RM items from the game's
 * items.dat extract), each resolved to the Gen 9 move it teaches through the
 * committed dex map, plus the shops that sell machines and the badge each
 * sale is gated on (marts.dat extract). Pickup timing for the rest is
 * curated in src/rejuv/move-sources.js. Reproducible from the repo alone:
 *
 *   node scripts/build-rejuv-move-sources.mjs
 *
 * A machine whose move has no Gen 9 identity (Rejuvenation's own moves,
 * Poison Sweep and the like) is listed under `unmapped` and left out of the
 * options: the engine's move tables are the generation's, so a move outside
 * them cannot be scored.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { Dex } = require('@pkmn/dex');

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rejuvDir = path.join(root, 'scripts', 'rejuv');
const load = (stem) =>
  JSON.parse(
    fs.readFileSync(path.join(rejuvDir, `${stem}.generated.json`), 'utf8'),
  );
const items = load('rejuv-items').data;
const marts = load('rejuv-marts').data;
const moveMap = load('rejuv-dex-map').moves;
const d9 = Dex.forGen(9);

const KINDS = { TM: 'tm', HM: 'hm', RM: 'rm' };
const machines = [];
const unmapped = [];
for (const [code, item] of Object.entries(items)) {
  const symbol = item.flags?.tm;
  if (!symbol) continue;
  const kind = KINDS[code.slice(0, 2)];
  if (!kind) continue;
  const mapped = moveMap[symbol];
  const move = mapped?.pkmnId ? d9.moves.get(mapped.pkmnId) : null;
  if (!move?.exists) {
    unmapped.push({ code, symbol });
    continue;
  }
  machines.push({ id: code.toLowerCase(), code, move: move.name, kind });
}
const byCode = (a, b) =>
  a.code.localeCompare(b.code, undefined, { numeric: true });
machines.sort(byCode);
unmapped.sort(byCode);

// Shops selling machines: shop id -> [{code, price, currency, badges}], where
// badges is the count a "$Trainer.numbadges >= N" condition demands (0 when
// the sale is unconditional).
const shops = {};
for (const [shop, mart] of Object.entries(marts)) {
  for (const entries of Object.values(mart.categories || {})) {
    if (!Array.isArray(entries)) continue;
    for (const entry of entries) {
      if (!entry.item || !/^(TM|HM|RM)\d/.test(entry.item)) continue;
      const badges = (entry.conditions || [])
        .map((condition) => /numbadges >= (\d+)/.exec(condition)?.[1])
        .filter(Boolean)
        .map(Number)
        .reduce((max, value) => Math.max(max, value), 0);
      (shops[shop] ||= []).push({
        code: entry.item,
        price: entry.price,
        currency: entry.currency,
        badges,
      });
    }
  }
}

const out = path.join(root, 'src', 'generated', 'rejuvMoveSources.generated.js');
fs.writeFileSync(
  out,
  `// Generated by scripts/build-rejuv-move-sources.mjs from the Rejuvenation
// V14 items.dat and marts.dat extracts and the Gen 9 dex map. Do not edit.

/**
 * Every machine the game distributes whose move the Gen 9 dex knows, by
 * code. \`kind\` is tm, hm, or rm (the Kristiline "RM" series).
 * @type {!Array<{id: string, code: string, move: string, kind: string}>}
 */
export const REJUV_MACHINES = ${JSON.stringify(machines, null, 2)};

/**
 * Machines teaching a move outside the Gen 9 dex (Rejuvenation's own moves);
 * listed for completeness, never offered as options.
 * @type {!Array<{code: string, symbol: string}>}
 */
export const REJUV_UNMAPPED_MACHINES = ${JSON.stringify(unmapped, null, 2)};

/**
 * Shops that sell machines, with the badge count each sale demands.
 * @type {!Object<string, !Array<{code: string, price: ?number,
 *     currency: string, badges: number}>>}
 */
export const REJUV_MACHINE_SHOPS = ${JSON.stringify(shops, null, 2)};
`,
);
console.log(
  `[rejuv-move-sources] ${machines.length} machines, ${unmapped.length} unmapped, ${Object.keys(shops).length} shops -> ${path.relative(root, out)}`,
);
